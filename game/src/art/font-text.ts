/** Accents are one row tall with a row of air under them: over the x-height in row 0 (where
 *  the dots of i and j sit), over capitals in row -2. So nothing rises above row 0 in running
 *  text, and a descender in the line above (rows 7-8) never touches an accent below it. The
 *  acute leans right of centre, the dot is one pixel: ź and ż stay apart. */
const acute = (x: number): [number, number][] => [[x, 0], [x + 1, 0]];
const acuteCap = (x: number): [number, number][] => [[x, -2], [x + 1, -2]];
const ogonek = (x: number): [number, number][] => [[x, 7], [x + 1, 8]];

