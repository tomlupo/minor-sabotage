// HUD symbols as one-bit masks (style guide §8): 12 x 12 icons for buttons, cards and tags,
// 7 x 9 head glyphs over a trooper or a guard, and 7 x 5 rank marks. Each is drawn here as
// rows of `#` and `.`; colours are applied by hud.ts.
import { parseSheets } from "./font";
import { mask, set, type Mask } from "./hud-kit";

function sheetMasks(src: string, rows: number, where: string): Map<string, Mask> {
  const out = new Map<string, Mask>();
  for (const [name, def] of parseSheets(src, rows, where)) {
    const m = mask(def.w, rows);
    for (const [x, y] of def.ink) set(m, x, y);
    out.set(name, m);
  }
  return out;
}

